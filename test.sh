#!/usr/bin/env bash
#
# Quick dev launcher (NO build, no publish).
#
#   ./test.sh            → asks ARM or Intel
#   ./test.sh arm        → launch ARM build
#   ./test.sh intel      → launch Intel build (via Rosetta on Apple Silicon)
#
# Injects the obfuscated Supabase secrets from .env.build (same as
# builder_sender.sh) then runs `tauri dev` for the chosen target. The app needs
# root for Mach VM reads, so it launches with sudo.

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
SECRETS_RS="${SCRIPT_DIR}/src-tauri/src/secrets.rs"
ENV_BUILD="${SCRIPT_DIR}/.env.build"

cyan() { printf "\033[36m%s\033[0m\n" "$*"; }
red()  { printf "\033[31m%s\033[0m\n" "$*" >&2; }
die()  { red "[X] $1"; exit 1; }
say()  { cyan "[*] $1"; }

# ─── Pick target ────────────────────────────────────────────────────
CHOICE="${1:-}"
if [ -z "${CHOICE}" ]; then
    read -r -p "Target [arm/intel]: " CHOICE
fi
case "$(printf '%s' "${CHOICE}" | tr '[:upper:]' '[:lower:]')" in
    arm|aarch64)  TARGET="aarch64-apple-darwin"; LABEL="ARM"   ;;
    intel|x86|x64|x86_64) TARGET="x86_64-apple-darwin"; LABEL="Intel" ;;
    *) die "Unknown target '${CHOICE}' (use: arm | intel)" ;;
esac

# ─── Inject obfuscated secrets ──────────────────────────────────────
[ -f "${ENV_BUILD}" ] || die ".env.build missing (copy .env.build.example and fill it in)"
set -a; . "${ENV_BUILD}"; set +a
: "${SUPABASE_URL:?Set SUPABASE_URL in .env.build}"
: "${SUPABASE_PUBLISHABLE_KEY:?Set SUPABASE_PUBLISHABLE_KEY in .env.build}"
: "${SOCRATE_HMAC_SECRET:?Set SOCRATE_HMAC_SECRET in .env.build (must match the Supabase secret)}"
case "${SUPABASE_PUBLISHABLE_KEY}" in
    sb_publishable_*|eyJ*) : ;;
    *) die "SUPABASE_PUBLISHABLE_KEY must be a publishable/anon key, not service_role" ;;
esac
cat > "${SECRETS_RS}" <<EOF
//! AUTO-GENERATED by test.sh — do not edit, do not commit.
use obfstr::obfstr;

pub fn supabase_url() -> String {
    obfstr!("${SUPABASE_URL}").to_owned()
}

pub fn supabase_anon_key() -> String {
    obfstr!("${SUPABASE_PUBLISHABLE_KEY}").to_owned()
}

pub fn supabase_hmac_secret() -> String {
    obfstr!("${SOCRATE_HMAC_SECRET}").to_owned()
}
EOF
say "Injected obfuscated Supabase secrets into secrets.rs"

# ─── Launch (no build) ──────────────────────────────────────────────
# Ensure the rustup target exists so dev doesn't stall asking for it.
if ! rustup target list --installed 2>/dev/null | grep -q "^${TARGET}$"; then
    say "Installing rustup target ${TARGET}..."
    rustup target add "${TARGET}"
fi

cd "${SCRIPT_DIR}"
say "Launching ${LABEL} (sudo, tauri dev)..."
exec sudo npm run tauri dev -- --target "${TARGET}"
